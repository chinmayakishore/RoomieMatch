const fs = require('fs');

function write(filePath, content) {
  const dir = require('path').dirname(filePath);
  require('fs').mkdirSync(dir, { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
  console.log('Created: ' + filePath);
}

// Fix useProfiles to exclude already matched profiles
write('src/hooks/useProfiles.js', [
  "import { useState, useEffect } from 'react';",
  "import { supabase } from '../lib/supabase';",
  "",
  "export default function useProfiles(currentUserId) {",
  "  const [profiles, setProfiles] = useState([]);",
  "  const [loading, setLoading] = useState(true);",
  "",
  "  useEffect(() => {",
  "    if (!currentUserId) { setLoading(false); return; }",
  "    fetchProfiles();",
  "  }, [currentUserId]);",
  "",
  "  const fetchProfiles = async () => {",
  "    // Get already matched user IDs",
  "    const { data: matchData } = await supabase",
  "      .from('matches')",
  "      .select('matched_user_id')",
  "      .eq('user_id', currentUserId);",
  "    const matchedIds = (matchData || []).map(m => m.matched_user_id);",
  "",
  "    // Fetch profiles excluding self and already matched",
  "    let query = supabase.from('profiles').select('*').neq('id', currentUserId);",
  "    if (matchedIds.length > 0) {",
  "      query = query.not('id', 'in', '(' + matchedIds.join(',') + ')');",
  "    }",
  "    const { data, error } = await query;",
  "    if (error) console.log('Error fetching profiles:', error);",
  "    setProfiles(data || []);",
  "    setLoading(false);",
  "  };",
  "",
  "  return { profiles, loading };",
  "}",
].join('\n'));

